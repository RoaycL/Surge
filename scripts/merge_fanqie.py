#!/usr/bin/env python3
"""Build the single FanQie module from reviewed, attributed source snapshots."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CANONICAL = 'Module/AdBlock/FanQieNovel.sgmodule'

def sections(text):
    result = {}; current = None
    for raw in text.lstrip('\ufeff').splitlines():
        line = raw.strip()
        if not line or line.startswith('#'): continue
        if line.startswith('['):
            if line not in ['[Rule]', '[URL Rewrite]', '[MITM]']:
                raise ValueError('Unreviewed FanQie section: ' + line)
            current = line; result.setdefault(current, [])
        elif current:
            result[current].append(line)
        else:
            raise ValueError('Unexpected FanQie input: ' + line)
    return result

def merge_fanqie(base, extra=None, dragon=None):
    if extra is None:
        extra = (ROOT / 'upstreams/FanQieNovel.yfamilys.plugin').read_text(encoding='utf-8-sig')
    if dragon is None:
        dragon = (ROOT / 'upstreams/fkikelee/lpx/DragonRead_remove_ads.lpx').read_text()
    rules = []; rewrites = []
    for source in [base, dragon, extra]:
        parsed = sections(source)
        for rule in parsed.get('[Rule]', []):
            fields = [x.strip() for x in rule.split(',')]
            if len(fields) not in [3, 4] or fields[0] not in ['DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD', 'IP-CIDR'] or fields[2] not in ['REJECT', 'DIRECT']:
                raise ValueError('Unreviewed FanQie rule: ' + rule)
            if fields[0] == 'DOMAIN' and any(c in fields[1] for c in '*?['):
                fields[0] = 'DOMAIN-WILDCARD'
            normalized = ','.join(fields)
            if normalized not in rules: rules.append(normalized)
        for line in parsed.get('[URL Rewrite]', []):
            if not line.endswith(' _ reject'):
                raise ValueError('Unreviewed FanQie rewrite: ' + line)
            line = line.replace(r'\.byteimg.com', r'\.byteimg\.com').replace(r'\.snssdk.com', r'\.snssdk\.com')
            if line not in rewrites: rewrites.append(line)
    header = '''#!name=番茄小说去广告（合并版）
#!desc=合并可莉与 zqzess 版本，拦截开屏、章末及广告 SDK 请求。含字节系广域拦截，可能影响其他字节系 App；HTTPS 重写需开启 MITM 并信任证书。请停用两个旧番茄模块，勿重复启用。
#!author=可莉🅥, zqzess；Surge 合并适配：RoaycL
#!category=去广告
#!homepage=https://github.com/RoaycL/Surge/blob/main/docs/fanqie-merge.md
#!icon=https://raw.githubusercontent.com/luestr/IconResource/main/App_icon/120px/DragonRead.png
#!date=__SOURCE_DATE__
# Merge revision: 2026-11-07
# Sources: upstreams/FanQieNovel.plugin; upstreams/fkikelee/lpx/DragonRead_remove_ads.lpx
# Additional source: https://yfamilys.com/plugin/fanqienovel.plugin (reviewed snapshot, not automatic live fetching)
# Generated by scripts/merge_fanqie.py; original authors retain attribution.
'''
    # These hosts cover every HTTPS URL rewrite above, avoiding the source's
    # incomplete hostname patterns and missing byteimg/snssdk interception.
    hosts = ['*.pangolin-sdk-toutiao.com', '*.pglstatp-toutiao.com', '*.pstatp.com', '*.snssdk.com', '*.byteimg.com']
    date = re.search(r'^#!date=(.*)$', dragon, re.M) or re.search(r'^#!date=(.*)$', base, re.M)
    header = header.replace('__SOURCE_DATE__', date[1].strip() if date else '2026-11-07')
    return header + '\n[Rule]\n' + '\n'.join(rules) + '\n\n[URL Rewrite]\n' + '\n'.join(rewrites) + '\n\n[MITM]\nhostname = %APPEND% ' + ', '.join(hosts) + '\n'

def main():
    text = merge_fanqie((ROOT / 'upstreams/FanQieNovel.plugin').read_text())
    (ROOT / CANONICAL).write_text(text)

if __name__ == '__main__': main()
