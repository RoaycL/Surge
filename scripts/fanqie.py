#!/usr/bin/env python3
"""Convert the yfamilys FanQie plugin to one Surge module."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CANONICAL = 'Module/AdBlock/FanQieNovel.sgmodule'
UPSTREAM = 'https://yfamilys.com/plugin/fanqienovel.plugin'

def sections(text):
    result = {}; current = None
    for raw in text.lstrip('\ufeff').splitlines():
        line = raw.strip()
        if not line or line.startswith('#'): continue
        if line.startswith('['):
            if line not in ['[Rule]', '[URL Rewrite]', '[MITM]']:
                raise ValueError('Unreviewed FanQie section: ' + line)
            current = line; result.setdefault(current, [])
        elif current:
            result[current].append(line)
        else:
            raise ValueError('Unexpected FanQie input: ' + line)
    return result

def convert_fanqie(source):
    rules = []; rewrites = []
    parsed = sections(source)
    for rule in parsed.get('[Rule]', []):
        fields = [x.strip() for x in rule.split(',')]
        if len(fields) not in [3, 4] or fields[0] not in ['DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD', 'IP-CIDR'] or fields[2] not in ['REJECT', 'DIRECT']:
            raise ValueError('Unreviewed FanQie rule: ' + rule)
        if fields[0] == 'DOMAIN' and any(c in fields[1] for c in '*?['):
            fields[0] = 'DOMAIN-WILDCARD'
        normalized = ','.join(fields)
        if normalized not in rules: rules.append(normalized)
    for line in parsed.get('[URL Rewrite]', []):
        if not line.endswith(' _ reject'):
            raise ValueError('Unreviewed FanQie rewrite: ' + line)
        line = line.replace(r'\.byteimg.com', r'\.byteimg\.com').replace(r'\.snssdk.com', r'\.snssdk\.com')
        if line not in rewrites: rewrites.append(line)
    if not rules:
        raise ValueError('FanQie upstream has no rules; refusing empty output')
    header = """#!name=番茄小说去广告（yfamilys）
#!desc=来自 yfamilys 的番茄小说去广告插件，自动跟随上游更新。含字节系广域拦截，可能影响其他字节系 App；HTTPS 重写需开启 MITM 并信任证书。
#!author=zqzess；Surge 适配：RoaycL
#!category=去广告
#!homepage=https://github.com/RoaycL/Surge/blob/main/docs/fanqie.md
#!icon=https://raw.githubusercontent.com/deezertidal/private/main/icons/fanqie.png
# Source: https://yfamilys.com/plugin/fanqienovel.plugin
# Generated by scripts/fanqie.py through scripts/sync_upstream.py.
"""
    date = re.search(r'^#!date=(.*)$', source, re.M)
    if date and date[1].strip():
        header = header.replace('# Source:', '#!date=' + date[1].strip() + '\n# Source:', 1)
    hosts = []
    for line in parsed.get('[MITM]', []):
        if '=' not in line or line.split('=', 1)[0].strip() != 'hostname':
            raise ValueError('Unreviewed FanQie MITM setting: ' + line)
        for host in line.split('=', 1)[1].split(','):
            host = host.strip()
            if host == '*.pangolin-sdk-toutiao': host = '*.pangolin-sdk-toutiao.com'
            elif host.endswith('.com.*'): host = host[:-2]
            elif host == '*.pangolin-sdk-toutiao.*': host = '*.pangolin-sdk-toutiao.com'
            if host and host not in hosts: hosts.append(host)
    # The current upstream omits hosts needed by its own HTTPS rewrites.
    for host in ['*.snssdk.com', '*.byteimg.com']:
        if host not in hosts: hosts.append(host)
    return header + '\n[Rule]\n' + '\n'.join(rules) + '\n\n[URL Rewrite]\n' + '\n'.join(rewrites) + '\n\n[MITM]\nhostname = %APPEND% ' + ', '.join(hosts) + '\n'

def main():
    text = convert_fanqie((ROOT / 'upstreams/FanQieNovel.plugin').read_text())
    (ROOT / CANONICAL).write_text(text)

if __name__ == '__main__': main()
